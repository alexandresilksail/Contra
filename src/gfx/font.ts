export const GLYPH_W = 5;
export const GLYPH_H = 7;

export interface TextOptions {
  color?: string;
  shadow?: string;
  scale?: number;
  align?: 'left' | 'center' | 'right';
  spacing?: number;
}

export function measureText(text: string, scale = 1, spacing = 1): number {
  const n = text.length;
  return n <= 0 ? 0 : (n * (GLYPH_W + spacing) - spacing) * scale;
}

function drawGlyph(
  ctx: CanvasRenderingContext2D,
  ch: string,
  x: number,
  y: number,
  scale: number,
  color: string,
): void {
  const rows = G[ch] ?? G[ch.toUpperCase()] ?? G['?'];
  ctx.fillStyle = color;
  for (let r = 0; r < GLYPH_H; r++) {
    const row = rows.split('/')[r] ?? '.....';
    let runStart = -1;
    for (let c = 0; c <= GLYPH_W; c++) {
      const on = c < GLYPH_W && row[c] === '#';
      if (on && runStart < 0) runStart = c;
      if (!on && runStart >= 0) {
        ctx.fillRect(x + runStart * scale, y + r * scale, (c - runStart) * scale, scale);
        runStart = -1;
      }
    }
  }
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  opt: TextOptions = {},
): void {
  const scale = opt.scale ?? 1;
  const spacing = opt.spacing ?? 1;
  const color = opt.color ?? '#ffffff';
  const str = String(text);
  const w = measureText(str, scale, spacing);
  let ox = x;
  if (opt.align === 'center') ox = Math.round(x - w / 2);
  else if (opt.align === 'right') ox = Math.round(x - w);
  const oy = Math.round(y);
  if (opt.shadow) {
    for (let i = 0; i < str.length; i++) {
      drawGlyph(ctx, str[i], ox + i * (GLYPH_W + spacing) * scale, oy + scale, scale, opt.shadow);
    }
  }
  for (let i = 0; i < str.length; i++) {
    drawGlyph(ctx, str[i], ox + i * (GLYPH_W + spacing) * scale, oy, scale, color);
  }
}
