#!/usr/bin/env node
/**
 * build-inventory — generate docs/assets/asset-inventory.csv (machine-readable)
 * and docs/assets/asset-inventory.md (human summary) from the scan JSONs
 * produced by scan-assets.mjs.
 *
 * Usage:
 *   node tools/assets/build-inventory.mjs \
 *     --current tools/assets/out/scan-current.json \
 *     --contra-unity tools/assets/out/scan-contra-unity.json \
 *     --hundouluo tools/assets/out/scan-hundouluo.json \
 *     --out-dir docs/assets
 *
 * Idempotent: identical inputs -> identical outputs (except the timestamp).
 */
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

function parseArgs(argv) {
  const args = { current: null, contraUnity: null, hundouluo: null, outDir: 'docs/assets' };
  for (let i = 2; i < argv.length; i++) {
    if (argv[i] === '--current') args.current = argv[++i];
    else if (argv[i] === '--contra-unity') args.contraUnity = argv[++i];
    else if (argv[i] === '--hundouluo') args.hundouluo = argv[++i];
    else if (argv[i] === '--out-dir') args.outDir = argv[++i];
    else throw new Error(`unknown arg: ${argv[i]}`);
  }
  return args;
}

const args = parseArgs(process.argv);

// current-project scan root is public/: it contains BOTH gitignored Konami
// sheets (sprites/) and the licensed Open Gunner vendor set (assets/vendor/),
// so the license columns must be decided per file, never blanket-labelled.
function currentProjectRow(f) {
  const p = f.relPath;
  if (p.startsWith('assets/vendor/open-gunner/') && /\.png$/i.test(p)) {
    return {
      license: 'LICENSE_VERIFIED',
      basis: 'CC-BY 3.0, Master484 (Open Gunner, OpenGameArt). Attribution shipped in assets/vendor/open-gunner/ATTRIBUTION.txt. Publishable.',
      integration: 'integrated-vendor (AssetRegistry)',
      verification: 'RUNTIME_VERIFIED',
      levels: 'stages 2-8 (registry-available; renderer switch is decision D-1)',
    };
  }
  if (p.startsWith('sprites/')) {
    return {
      license: 'THIRD_PARTY_RESTRICTED',
      basis: 'Konami NES ripped sheets supplied by the user for local use only; gitignored, never distributed.',
      integration: 'integrated-local',
      verification: 'RUNTIME_VERIFIED',
      levels: 'level-01 (+ shared by all stages)',
    };
  }
  return {
    license: 'PROJECT_ORIGINAL',
    basis: 'Generated by the project asset pipeline (tools/assets/); no third-party rights involved.',
    integration: 'pipeline-generated',
    verification: 'RUNTIME_VERIFIED',
    levels: 'all stages (shared)',
  };
}

const REPO_META = {
  'current-project': {
    url: 'https://github.com/alexandresilksail/Contra (private)',
    commit: 'f1ed33f (local worktree)',
    rowFor: currentProjectRow,
  },
  'contra-unity': {
    url: 'https://github.com/RanZelong/Contra-Unity',
    commit: 'b8a4430c3ea007101971aaf4443c1366ccc33d4a',
    licenseFor: (f) => {
      if (f.relPath.startsWith('Assets/Mirror/') || f.relPath.startsWith('Assets/ParrelSync/') || f.relPath.startsWith('Assets/Sirenix/')) return 'THIRD_PARTY_RESTRICTED';
      if (f.category === 'code/csharp') return 'LICENSE_PARTIAL';
      if (f.category.startsWith('image/') || f.category.startsWith('audio/')) return 'THIRD_PARTY_RESTRICTED';
      return 'LICENSE_PARTIAL';
    },
    basis: 'Repo code is GPL-3.0 (copyleft). Art/audio are uncredited NES rips (© Konami) — no redistribution right. Vendored plugins keep their own licenses.',
    integration: 'not-integrated (isolated audit only)',
    verification: 'STATIC_CONFIRMED',
    levels: 'level-01 only',
  },
  hundouluo: {
    url: 'https://github.com/nan896/hundouluo',
    commit: 'dd60029 (single commit, 2026-09-18)',
    licenseFor: () => 'PERMISSION_REQUIRED',
    basis: 'No LICENSE file in the repo — all rights reserved; nothing may be copied without permission.',
    integration: 'not-integrated (isolated audit only)',
    verification: 'STATIC_CONFIRMED',
    levels: 'level-01 only (its own single stage)',
  },
};

function load(p) {
  return p ? JSON.parse(readFileSync(path.resolve(p), 'utf8')) : null;
}

function rowFields(meta, f) {
  if (meta.rowFor) return meta.rowFor(f);
  return {
    license: meta.licenseFor(f),
    basis: meta.basis,
    integration: meta.integration,
    verification: meta.verification,
    levels: meta.levels,
  };
}

const scans = [args.current, args.contraUnity, args.hundouluo].filter(Boolean).map(load);
const rows = [];
for (const scan of scans) {
  const meta = REPO_META[scan.roots[0].repo] || { url: '?', commit: '?', licenseFor: () => 'LICENSE_UNKNOWN', basis: '', integration: 'not-integrated', verification: 'NOT_VERIFIED', levels: '?' };
  for (const f of scan.files) {
    const rf = rowFields(meta, f);
    rows.push({
      asset_id: `${scan.roots[0].repo}/${f.relPath}`,
      repo: scan.roots[0].repo,
      repo_url: meta.url,
      repo_commit: meta.commit,
      rel_path: f.relPath,
      filename: path.basename(f.relPath),
      format: f.format || f.ext.replace('.', ''),
      width: f.width ?? '',
      height: f.height ?? '',
      bytes: f.bytes,
      sha256: f.sha256,
      category: f.category,
      license_status: rf.license,
      license_basis: rf.basis,
      integration_status: rf.integration,
      verification_status: rf.verification,
      levels: rf.levels,
      notes: '',
    });
  }
}

const cols = Object.keys(rows[0] || { asset_id: '' });
const csvEscape = (v) => {
  const s = String(v ?? '');
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
const csv = [cols.join(','), ...rows.map((r) => cols.map((c) => csvEscape(r[c])).join(','))].join('\n') + '\n';

mkdirSync(path.resolve(args.outDir), { recursive: true });
writeFileSync(path.join(path.resolve(args.outDir), 'asset-inventory.csv'), csv);

// ---------- markdown summary ----------
const byRepo = {};
for (const r of rows) {
  byRepo[r.repo] = byRepo[r.repo] || { total: 0, bytes: 0, byCat: {}, byFmt: {}, images: [], audio: [] };
  const b = byRepo[r.repo];
  b.total++;
  b.bytes += Number(r.bytes);
  b.byCat[r.category] = (b.byCat[r.category] || 0) + 1;
  b.byFmt[r.format] = (b.byFmt[r.format] || 0) + 1;
  if (r.category.startsWith('image/')) b.images.push(r);
  if (r.category.startsWith('audio/')) b.audio.push(r);
}

const fmtBytes = (n) => (n >= 1 << 20 ? `${(n / (1 << 20)).toFixed(1)} MB` : `${(n / 1024).toFixed(1)} KB`);
let md = `# 素材资产清单（Asset Inventory）\n\n`;
md += `> 由 \`tools/assets/build-inventory.mjs\` 从三个扫描根生成（幂等）。机器可读版本：\n> \`asset-inventory.csv\`（${rows.length} 行）。\n\n`;
md += `| 仓库 | 地址 | Commit | 文件数 | 总大小 |\n|---|---|---|---|---|\n`;
for (const [repo, b] of Object.entries(byRepo)) {
  const meta = REPO_META[repo];
  md += `| ${repo} | ${meta.url} | \`${String(meta.commit).slice(0, 12)}\` | ${b.total} | ${fmtBytes(b.bytes)} |\n`;
}
md += `\n## 分类统计\n\n| 仓库 | 类别分布 | 格式分布 |\n|---|---|---|\n`;
for (const [repo, b] of Object.entries(byRepo)) {
  const cats = Object.entries(b.byCat).sort((x, y) => y[1] - x[1]).map(([k, v]) => `${k}×${v}`).join(', ');
  const fmts = Object.entries(b.byFmt).sort((x, y) => y[1] - x[1]).map(([k, v]) => `${k}×${v}`).join(', ');
  md += `| ${repo} | ${cats} | ${fmts} |\n`;
}

for (const [repo, b] of Object.entries(byRepo)) {
  if (!b.images.length && !b.audio.length) continue;
  md += `\n## ${repo} — 图像资源（${b.images.length}）\n\n`;
  md += `| 文件 | 格式 | 尺寸 | 字节 | SHA-256(前12) | 类别 | 授权 |\n|---|---|---|---|---|---|---|\n`;
  for (const r of b.images) {
    md += `| \`${r.rel_path}\` | ${r.format} | ${r.width}×${r.height} | ${r.bytes} | \`${String(r.sha256).slice(0, 12)}\` | ${r.category} | ${r.license_status} |\n`;
  }
  if (b.audio.length) {
    md += `\n## ${repo} — 音频资源（${b.audio.length}）\n\n`;
    md += `| 文件 | 格式 | 字节 | SHA-256(前12) | 类别 | 授权 |\n|---|---|---|---|---|---|\n`;
    for (const r of b.audio) {
      md += `| \`${r.rel_path}\` | ${r.format} | ${r.bytes} | \`${String(r.sha256).slice(0, 12)}\` | ${r.category} | ${r.license_status} |\n`;
    }
  }
}

writeFileSync(path.join(path.resolve(args.outDir), 'asset-inventory.md'), md);
process.stderr.write(`build-inventory: ${rows.length} rows -> ${path.resolve(args.outDir)}/asset-inventory.{csv,md}\n`);
